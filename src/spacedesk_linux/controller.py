"""Manage only this application's bridge services and isolated browser profiles."""
import fcntl
import json
import os
import shlex
import shutil
import signal
import socket
import subprocess
import sys
import time
import tempfile
from concurrent.futures import ThreadPoolExecutor
import urllib.error
import urllib.request
from contextlib import contextmanager
from pathlib import Path

from . import config as settings
from .displays import detect
from .paths import CACHE_DIR, RUNTIME_CONFIG, RUNTIME_DIR


def service(key):
    return f"spacedesk-linux@{key}.service"


def device_name(screen):
    return "screen-" + screen["id"]


def profile(screen):
    return CACHE_DIR / ("chrome-" + screen["id"])


def configure_browser_profile(screen):
    """Disable automatic translation offers only in this app's stopped profile."""
    if browser_pids(screen):
        raise RuntimeError("El visor debe estar cerrado antes de configurar su perfil.")
    directory = profile(screen) / "Default"
    path = directory / "Preferences"
    try:
        preferences = json.loads(path.read_text()) if path.exists() else {}
        if not isinstance(preferences, dict) or not isinstance(preferences.get("translate", {}), dict):
            raise ValueError("formato inesperado")
    except (ValueError, OSError) as error:
        raise RuntimeError(f"No se modificó el perfil del visor: {error}") from error
    preferences.setdefault("translate", {})["enabled"] = False
    directory.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", dir=directory, delete=False) as stream:
            temporary = Path(stream.name)
            json.dump(preferences, stream)
            stream.write("\n")
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def browser_pids(screen):
    expected = f"--user-data-dir={profile(screen)}"
    matches = []
    for entry in Path("/proc").iterdir():
        if not entry.name.isdigit():
            continue
        try:
            args = shlex.split((entry / "cmdline").read_bytes().decode(errors="replace").replace("\0", " "))
            if (args and Path(args[0]).name in {"chrome", "chromium", "chromium-browser"}
                    and expected in args and not any(a.startswith("--type=") for a in args)):
                matches.append(int(entry.name))
        except (FileNotFoundError, PermissionError, ProcessLookupError, ValueError):
            pass
    return matches


def close_browser(screen):
    for pid in browser_pids(screen):
        try:
            os.kill(pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
    for _ in range(50):
        if not browser_pids(screen):
            return
        time.sleep(0.1)
    raise RuntimeError("El visor aun esta cerrandose; no se abrira un duplicado.")


def status(screen):
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{screen['port']}/status", timeout=0.7) as response:
            value = json.load(response)
        if value.get("name") != device_name(screen):
            return {"state": "conflict", "message": f"Puerto {screen['port']} ocupado por otra aplicacion."}
        return value
    except (OSError, ValueError, urllib.error.URLError):
        return {"state": "stopped", "message": "Detenido"}


def environment(config, screen, display):
    width, height = settings.resolution(screen, display)
    return (f"SPACEDESK_DRIVER={config['host']}\n"
            f"SPACEDESK_HTTP_HOST=127.0.0.1\nSPACEDESK_HTTP_PORT={screen['port']}\n"
            f"SPACEDESK_NAME={device_name(screen)}\n"
            f"SPACEDESK_WIDTH={width}\nSPACEDESK_HEIGHT={height}\n"
            f"SPACEDESK_QUALITY={config['quality']}\nSPACEDESK_FPS=0\nSPACEDESK_AUTORECONNECT=0\n")


@contextmanager
def operation_lock():
    RUNTIME_DIR.mkdir(parents=True, exist_ok=True)
    with (RUNTIME_DIR / "spacedesk-linux-control.lock").open("w") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise RuntimeError("Hay otra operacion de spacedesk en curso.") from None
        yield


class Controller:
    def __init__(self, config, displays=None):
        settings.validate(config)
        self.config = config
        self.displays = displays

    def statuses(self):
        return {screen["id"]: status(screen) for screen in self.config["screens"]}

    def _stop_screen(self, screen):
        subprocess.run(["systemctl", "--user", "stop", service(screen["id"])], check=True, timeout=8)
        close_browser(screen)

    def stop(self):
        with operation_lock():
            keys = {s["id"] for s in self.config["screens"]}
            if RUNTIME_CONFIG.exists():
                keys.update(p.stem for p in RUNTIME_CONFIG.glob("*.env"))
            screens = []
            for key in sorted(keys):
                # Only instance IDs generated by this application are managed.
                if not key or any(c not in "abcdefghijklmnopqrstuvwxyz0123456789-" for c in key):
                    continue
                screens.append({"id": key})
            # Notify all Windows displays together, not one browser timeout at a time.
            if screens:
                with ThreadPoolExecutor(max_workers=min(4, len(screens))) as executor:
                    futures = [executor.submit(self._stop_screen, screen) for screen in screens]
                    errors = []
                    for future in futures:
                        try:
                            future.result()
                        except Exception as error:
                            errors.append(str(error))
                    if errors:
                        raise RuntimeError("No se pudieron cerrar todos los visores: " + "; ".join(errors))

    def connect(self):
        displays = self.displays if self.displays is not None else detect()
        settings.validate(self.config, displays, connecting=True)
        by_connector = {display.connector: display for display in displays}
        enabled = [s for s in self.config["screens"] if s["enabled"]]
        if not enabled:
            self.stop()
            return self.statuses()
        browser = next((shutil.which(name) for name in ("google-chrome", "chromium", "chromium-browser")
                        if shutil.which(name)), None)
        if browser is None:
            raise RuntimeError("Instala Google Chrome o Chromium para mostrar los visores.")
        with operation_lock():
            RUNTIME_CONFIG.mkdir(parents=True, exist_ok=True)
            for screen in self.config["screens"]:
                if not screen["enabled"] and (RUNTIME_CONFIG / f"{screen['id']}.env").exists():
                    self._stop_screen(screen)
            for screen in enabled:
                self._connect_screen(screen, by_connector[screen["connector"]], browser)
        return self.statuses()

    def _connect_screen(self, screen, display, browser):
        current = status(screen)
        if current["state"] == "conflict":
            raise RuntimeError(current["message"])
        env_path = RUNTIME_CONFIG / f"{screen['id']}.env"
        value = environment(self.config, screen, display)
        changed = not env_path.exists() or env_path.read_text() != value
        if changed and browser_pids(screen):
            close_browser(screen)
        if current["state"] == "stopped":
            try:
                with socket.socket() as probe:
                    # Match HTTPServer's reuse policy: TIME_WAIT is not a listener.
                    probe.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
                    probe.bind(("127.0.0.1", screen["port"]))
            except OSError:
                raise RuntimeError(f"El puerto {screen['port']} esta ocupado.") from None
        env_path.write_text(value)
        env_path.chmod(0o600)
        subprocess.run(["systemctl", "--user", "restart" if changed else "start", service(screen["id"])], check=True)
        for _ in range(50):
            current = status(screen)
            if current["state"] != "stopped":
                break
            time.sleep(0.1)
        else:
            raise RuntimeError("El servicio no arranco. Ejecuta el instalador por usuario del proyecto.")
        if browser_pids(screen) and current["state"] != "streaming":
            close_browser(screen)
        if not browser_pids(screen):
            directory = profile(screen)
            configure_browser_profile(screen)
            with (CACHE_DIR / f"{screen['id']}.log").open("a") as log:
                subprocess.Popen([browser, f"--user-data-dir={directory}", "--no-first-run",
                                  "--no-default-browser-check", "--disable-session-crashed-bubble",
                                  f"--app=http://127.0.0.1:{screen['port']}/"],
                                 stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
        for _ in range(100):
            current = status(screen)
            if current["state"] == "streaming" and browser_pids(screen):
                self._place(screen, display)
                return
            if current["state"] in {"disconnected", "conflict"}:
                raise RuntimeError(current["message"])
            time.sleep(0.15)
        raise RuntimeError(f"{screen['connector']}: Windows no envio imagen. No se reintentara en bucle.")

    def _place(self, screen, display):
        env = os.environ.copy()
        root = str(Path(__file__).resolve().parent.parent)
        env["PYTHONPATH"] = root + os.pathsep + env.get("PYTHONPATH", "")
        subprocess.run([sys.executable, "-m", "spacedesk_linux.window", "--pids",
                        ",".join(map(str, browser_pids(screen))), str(display.x), str(display.y),
                        str(display.width), str(display.height)], env=env, check=True, timeout=15)
